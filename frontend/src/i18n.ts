/* ═══════════════════════════════════════════════════════════════
   i18n — Mrs.D UI translation system
   English, Telugu, Hindi, Tamil, Kannada, Malayalam
   Persists the selected language in localStorage, translates
   instantly without reloading the page.
═══════════════════════════════════════════════════════════════ */

export type SupportedLanguage =
  | "English"
  | "Telugu"
  | "Hindi"
  | "Tamil"
  | "Kannada"
  | "Malayalam";

export const SUPPORTED_LANGUAGES: SupportedLanguage[] = [
  "English",
  "Telugu",
  "Hindi",
  "Tamil",
  "Kannada",
  "Malayalam",
];

const STORAGE_KEY = "mrsd_ui_language";

export function getStoredLanguage(): SupportedLanguage {
  if (typeof window === "undefined") return "English";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved && (SUPPORTED_LANGUAGES as string[]).includes(saved)) {
    return saved as SupportedLanguage;
  }
  return "English";
}

export function storeLanguage(lang: SupportedLanguage) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(STORAGE_KEY, lang);
}

